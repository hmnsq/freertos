        *px_چوٹی_دا_ڈھیر = 0xaaaaaaaa;
        px_چوٹی_دا_ڈھیر--;
        *px_چوٹی_دا_ڈھیر = 0x99999999;
        px_چوٹی_دا_ڈھیر--;
